let sidebarEl = null;
let isCollapsed = false;
let isMobileOpen = false;

/**
 * Render sidebar
 * @returns {HTMLElement}
 */
export function renderSidebar() {
  sidebarEl = document.createElement('aside');
  sidebarEl.className = 'sidebar';

  sidebarEl.innerHTML = `
    <div class="sidebar-header">
      <div class="sidebar-logo">SF</div>
      <span class="sidebar-title">SolidFit</span>
    </div>
    <nav class="sidebar-nav">
      ${navItems.map(item => `
        <div class="sidebar-nav-item" data-path="${item.path}" data-id="${item.id}">
          <span class="sidebar-nav-item-icon">${icons[item.icon]}</span>
          <span class="sidebar-nav-item-label">${item.label}</span>
        </div>
      `).join('')}
    </nav>
    <div class="sidebar-footer">
      <button class="btn btn-ghost btn-icon sidebar-toggle" title="Toggle Sidebar">
        <span class="sidebar-toggle-icon">${icons.menu}</span>
      </button>
    </div>
  `;

  // Add event listeners
  sidebarEl.querySelectorAll('.sidebar-nav-item').forEach(item => {
    item.addEventListener('click', () => {
      navigate(item.dataset.path);
      if (isMobileOpen) {
        closeMobileSidebar();
      }
    });
  });

  const toggleBtn = sidebarEl.querySelector('.sidebar-toggle');
  if (toggleBtn) {
    toggleBtn.addEventListener('click', () => {
      if (window.innerWidth <= 768) {
        toggleMobileSidebar();
      } else {
        toggleCollapse();
      }
    });
  }

  updateActiveNav();

  return sidebarEl;
}

/**
 * Update active nav item
 */
export function updateActiveNav() {
  const currentPath = getCurrentRoute();
  if (!sidebarEl) return;

  sidebarEl.querySelectorAll('.sidebar-nav-item').forEach(item => {
    if (item.dataset.path === currentPath) {
      item.classList.add('active');
    } else {
      item.classList.remove('active');
    }
  });
}

/**
 * Toggle sidebar collapse
 */
function toggleCollapse() {
  isCollapsed = !isCollapsed;
  if (sidebarEl) {
    sidebarEl.classList.toggle('collapsed', isCollapsed);
  }
}

/**
 * Toggle mobile sidebar
 */
export function toggleMobileSidebar() {
  isMobileOpen = !isMobileOpen;
  if (sidebarEl) {
    sidebarEl.classList.toggle('mobile-open', isMobileOpen);
  }
}

/**
 * Close mobile sidebar
 */
function closeMobileSidebar() {
  isMobileOpen = false;
  if (sidebarEl) {
    sidebarEl.classList.remove('mobile-open');
  }
}

/**
 * Get icon SVG
 * @param {string} name
 * @returns {string}
 */
export function getIcon(name) {
  return icons[name] || '';
}

